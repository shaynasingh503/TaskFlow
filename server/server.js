import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
import morgan from 'morgan';
import { mkdirSync } from 'fs';
import { connectDB } from './config/db.js';
import authRoutes from './routes/authRoutes.js';
import employeeRoutes from './routes/employeeRoutes.js';
import taskRoutes from './routes/taskRoutes.js';
import dashboardRoutes from './routes/dashboardRoutes.js';
import { getTasks } from './controllers/taskController.js';
import { authorize, protect } from './middleware/auth.js';
import { errorHandler, notFound } from './middleware/error.js';
dotenv.config(); mkdirSync('uploads', { recursive: true }); await connectDB();
const app = express();
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173' })); app.use(express.json()); app.use(morgan('dev')); app.use('/uploads', express.static('uploads'));
app.get('/api/health', (req, res) => res.json({ status: 'ok' }));
app.use('/api/auth', authRoutes); app.use('/api/employees', employeeRoutes); app.use('/api/tasks', taskRoutes); app.use('/api/dashboard', dashboardRoutes);
app.get('/api/employee/tasks', protect, authorize('employee'), getTasks);
app.use(notFound); app.use(errorHandler);
app.listen(process.env.PORT || 5000, () => console.log(`API running on port ${process.env.PORT || 5000}`));
